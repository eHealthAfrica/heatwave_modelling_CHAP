"""Grouped SHAP, grouped permutation importance and the LightGBM ablation ladder on validation
(DEC-01); writes docs/forecast/EXPLAINABILITY.md.

    python scripts/forecast_explain.py

Uses the Phase 12 settings in docs/forecast/MODEL_SELECTION.json, refits the selected model per
lead on the training split and explains it on 2015-2020. Read-only on the frozen data; no Earth
Engine access; test rows are never built. Exit codes: 0 ok, 2 bad arguments.
"""
