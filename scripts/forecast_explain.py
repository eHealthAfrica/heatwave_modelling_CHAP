GENERATED_MARKER = "<!-- generated by scripts/forecast_explain.py -->"
DOCS_ROOT = REPO_ROOT / "docs"
DEFAULT_DOCS_OUT = DOCS_ROOT / "forecast" / "EXPLAINABILITY.md"
DEFAULT_SELECTION = DOCS_ROOT / "forecast" / "MODEL_SELECTION.json"
SHAP_ROWS = 50_000


def _log(msg):
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def _bad(msg):
    print(f"error: {msg}", file=sys.stderr)
    return 2


def _inside(path: Path, base: Path) -> bool:
    base = base.resolve()
    return path == base or base in path.parents


def _f(x, nd=4):
    return f"{float(x):.{nd}f}" if x is not None and math.isfinite(float(x)) else "n/a"


def _json_safe(obj):
    if isinstance(obj, dict):
        return {str(k): _json_safe(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_json_safe(v) for v in obj]
    if isinstance(obj, np.generic):
        obj = obj.item()
    if isinstance(obj, float) and not math.isfinite(obj):
        return None
    return obj


def render(meta, perm, shap, ladder) -> str:
    L = ["# Explainability: grouped SHAP, grouped permutation importance and ablation (2015-2020)", "",
         CAPTION_VALIDATION, "",
         f"Run `{meta['run_id']}`, generated {meta['generated_utc']}. Config sha256 `{meta['config_sha256'][:12]}…`. "
         "Models are the Phase 12 selections per lead (settings from `MODEL_SELECTION.json`), refitted on the "
         "training split and explained on the validation years, before recalibration (a monotone recalibration "
         "does not change rankings or SHAP attributions).", "",
         "Feature groups follow the ablation ladder: " + "; ".join(
             f"**{g}** ({len(n)})" for g, n in meta["groups"].items()) + ".", "",
         "These describe what the fitted models use, not causes. Correlated groups share credit.", "",
         "## 1. Grouped permutation importance (rise in validation Brier when a group is shuffled)", ""]
    leads = sorted(perm, key=int)
    groups = list(meta["groups"])
    L.append("| Group | " + " | ".join(f"Lead {k} ({meta['model'][k]})" for k in leads) + " |")
    L.append("|---|" + "---|" * len(leads))
    for g in groups:
        cells = []
        for k in leads:
            r = next(x for x in perm[k] if x["group"] == g)
            cells.append(f"{1e4 * r['delta_brier_mean']:+.1f} ± {1e4 * r['delta_brier_sd']:.1f}")
        L.append(f"| {g} | " + " | ".join(cells) + " |")
    L += ["", "Values are Brier rises × 10⁻⁴ (mean ± sd over 3 shuffles). For scale, damped persistence beats "
          "recent climatology at lead 1 by about 116 × 10⁻⁴.", "",
          f"## 2. Grouped SHAP (share of mean |contribution|, log-odds scale, {SHAP_ROWS:,} validation rows)", "",
          "| Group | " + " | ".join(f"Lead {k}" for k in leads) + " |", "|---|" + "---|" * len(leads)]
    for g in groups:
        cells = []
        for k in leads:
            r = next(x for x in shap[k] if x["group"] == g)
            cells.append(f"{100 * r['share']:.1f}%")
        L.append(f"| {g} | " + " | ".join(cells) + " |")
    L += ["", "## 3. Ablation ladder with the tuned LightGBM (validation Brier; exploratory, no CIs)", "",
          f"Reference Brier: recent_climatology and damped_persistence per lead in the last rows. Phase 11 has "
          "the same ladder for logistic regression with paired CIs.", ""]
    lk = sorted(ladder, key=int)
    L.append("| Step | Features | " + " | ".join(f"Lead {k} Brier | Lead {k} BSS vs recent" for k in lk) + " |")
    L.append("|---|---|" + "---|---|" * len(lk))
    steps = [s["step"] for s in ladder[lk[0]]["steps"]]
    for i, st in enumerate(steps):
        cells = []
        for k in lk:
            s = ladder[k]["steps"][i]
            cells += [_f(s["brier"]), f"{s['bss_recent']:+.3f}"]
        L.append(f"| {st} | {ladder[lk[0]]['steps'][i]['n_features']} | " + " | ".join(cells) + " |")
    for ref in ("recent_climatology", "damped_persistence"):
        cells = []
        for k in lk:
            b, r0 = ladder[k]["ref"][ref], ladder[k]["ref"]["recent_climatology"]
            cells += [_f(b), f"{1 - b / r0:+.3f}"]
        L.append(f"| _{ref}_ | – | " + " | ".join(cells) + " |")
    L += ["", "## Notes", "",
          "- Labels are ERA5-Land reanalysis heatwave weeks (3+ heatwave days), not station-confirmed.",
          "- The heatwave detection layer is rule-based and separate from this trained forecast layer.",
          "- Test years 2021-2026 were not touched by this analysis.", "", GENERATED_MARKER, ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data-root", default=None)
    ap.add_argument("--runs-root", default=None)
    ap.add_argument("--selection", default=str(DEFAULT_SELECTION))
    ap.add_argument("--docs-out", default=str(DEFAULT_DOCS_OUT))
    ap.add_argument("--config", default=str(FORECAST_CONFIG_PATH))
    ap.add_argument("--expected-parquet-sha256", default=None)
    ap.add_argument("--ladder-leads", default="1,2")
    ap.add_argument("--max-train-rows", type=int, default=MAX_TRAIN_ROWS)
    ap.add_argument("--shap-rows", type=int, default=SHAP_ROWS)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    try:
        cfg = load_forecast_config(Path(args.config))
        sel = json.loads(Path(args.selection).read_text(encoding="utf-8"))["by_lead"]
        ladder_leads = [int(t) for t in args.ladder_leads.split(",") if t.strip()]
    except (ValueError, OSError, KeyError) as exc:
        return _bad(str(exc))
    leads = sorted(int(k) for k in sel)
    if not set(ladder_leads) <= set(leads):
        return _bad("--ladder-leads must be leads in the selection")
    if args.expected_parquet_sha256:
        import dataclasses
        cfg = dataclasses.replace(cfg, data=dataclasses.replace(cfg.data, expected_parquet_sha256=args.expected_parquet_sha256))
    data_root = Path(args.data_root) if args.data_root else Path(settings.local_data_dir)
    runs_root = Path(args.runs_root) if args.runs_root else data_root
    if _inside((runs_root / RUNS_SUBDIR).resolve(), REPO_ROOT):
        return _bad("--runs-root must not be inside the repository")
    docs_out = Path(args.docs_out).resolve()
    if not args.force and not _inside(docs_out, DOCS_ROOT):
        return _bad(f"--docs-out must be under {DOCS_ROOT} (or pass --force)")

    _log("loading frozen data")
    panel = load_panel(cfg.data, data_root)
    static = load_static(cfg.data, panel.wards, data_root)
    clim = Climatology.fit(panel, cfg.splits.train_end)
    store = build_feature_store(panel, clim, static)
    fctx = baselines.FitContext(panel, static, clim, cfg)
    names = full_feature_set()
    groups = explain.feature_groups()

    with run_folder(cfg, data_sha256=panel.sha256, data_root=runs_root) as rctx:
        refs = baselines.fit_baselines(fctx, names=["recent_climatology", "damped_persistence"])
        perm, shap, ladder, model_by_lead = {}, {}, {}, {}
        for lead in leads:
            s = sel[str(lead)]
            base = s["selected"].removesuffix("_cal")
            model_by_lead[str(lead)] = base
            _log(f"lead {lead}: fitting {base}")
            wv, ov = dataset.lead_row_index(panel, cfg, lead, "validate")
            X = design_matrix(store, panel, static, cfg, names, lead, wv, ov, dtype=np.float32)
            y = targets.lead_label(panel, lead)[wv, ov].astype(np.float64)
            if base == "lightgbm":
                m = lgbm.LightGBMForecaster(store, {lead: s["lgb_params"]}, {lead: s["n_estimators"]},
                                            max_train_rows=args.max_train_rows).fit(fctx, (lead,))
                est = m.models[lead]
                predict = lambda Z, est=est: est.predict_proba(Z)[:, 1]  # noqa: E731
            else:
                m = LogisticForecaster(store, max_train_rows=args.max_train_rows).fit(fctx, (lead,))
                mdl, mu, sc = m.models[lead], m.mean_[lead], m.scale_[lead]
                predict = lambda Z, mdl=mdl, mu=mu, sc=sc: mdl.predict_proba((Z.astype(np.float64) - mu) / sc)[:, 1]  # noqa: E731
            _log(f"lead {lead}: grouped permutation importance")
            perm[str(lead)] = explain.grouped_permutation(predict, X, y, names, groups)
            rng = np.random.default_rng([cfg.seed, lead, 14])
            sub = np.sort(rng.choice(X.shape[0], min(args.shap_rows, X.shape[0]), replace=False))
            if base == "lightgbm":
                contrib = explain.lightgbm_contributions(est, X[sub])
            else:
                contrib = explain.logistic_contributions(mdl, mu, sc, X[sub])
            shap[str(lead)] = explain.grouped_contributions(contrib, names, groups)
            if lead in ladder_leads:
                ref = {nm: explain.brier(refs[nm].predict(lead, wv, ov), y) for nm in refs}
                steps = []
                for label, feats in ablation_ladder():
                    _log(f"lead {lead}: ladder step {label}")
                    fm = lgbm.LightGBMForecaster(store, {lead: s["lgb_params"]}, {lead: s["n_estimators"]},
                                                 feature_names=feats, max_train_rows=args.max_train_rows).fit(fctx, (lead,))
                    b = explain.brier(fm.predict(lead, wv, ov), y)
                    steps.append({"step": label, "n_features": len(feats), "brier": b,
                                  "bss_recent": 1 - b / ref["recent_climatology"]})
                ladder[str(lead)] = {"steps": steps, "ref": ref}
            del X

        meta = dict(run_id=rctx.run_id, generated_utc=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                    config_sha256=config_hash(cfg), groups={g: list(n) for g, n in groups.items()},
                    model=model_by_lead)
        md = render(meta, perm, shap, ladder)
        (rctx.path / "explain_results.json").write_text(json.dumps(_json_safe(
            {"meta": meta, "permutation": perm, "shap": shap, "ladder": ladder}), indent=1, allow_nan=False),
            encoding="utf-8")
        (rctx.path / "EXPLAINABILITY.md").write_text(md, encoding="utf-8")
        docs_out.parent.mkdir(parents=True, exist_ok=True)
        tmp = docs_out.with_name(docs_out.name + ".tmp")
        tmp.write_text(md, encoding="utf-8")
        os.replace(tmp, docs_out)
    print(f"run folder: {rctx.path}")
    print(f"docs report: {docs_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
