"""Go/no-go decision (GATE.json) and the stakeholder report (docs/FORECAST_REPORT.md) for the single
test evaluation (DEC-02, DEC-03, DEC-04).

Everything here works on the JSON form of the harness results (``harness.results_to_dict``), so
the decision and report can be rebuilt from the run folder without scoring again.
"""
from __future__ import annotations

import math

from heatwave.forecast import targets
from heatwave.forecast.evaluation.lightgbm_report import BIN_TOL, CITL_TOL, MIN_BIN_SHARE
from heatwave.forecast.report import CAPTION

GENERATED_MARKER = "<!-- generated by scripts/forecast_test.py -->"
CAPTION_TEST = CAPTION + "; test 2021-2026, scored once"
CANDIDATE = "forecast"
RAW = "forecast_raw"


def _ok(x) -> bool:
    return x is not None and isinstance(x, (int, float)) and math.isfinite(float(x))


def _f(x, nd=4) -> str:
    return f"{float(x):.{nd}f}" if _ok(x) else "n/a"


def _ci(lo, hi, nd=3) -> str:
    return f"[{_f(lo, nd)}, {_f(hi, nd)}]" if _ok(lo) and _ok(hi) else "n/a"


def comparison(res: dict, ref: str, cand: str = CANDIDATE):
    for r in res["comparisons"]:
        if r["reference"] == ref and r["candidate"] == cand:
            return r
    return None


def brier(res: dict, name: str):
    for r in res["summary"]:
        if r["predictor"] == name:
            return r["brier"]
    return None


def lead_passes(row, threshold: float) -> bool:
    """Pre-registered rule: BSS above the threshold and the week-block CI lower bound above it too."""
    return bool(row is not None and _ok(row["bss"]) and _ok(row["bss_week_lo"])
                and row["bss"] > threshold and row["bss_week_lo"] > threshold)


def decide(results: dict, references: dict, primary_leads, threshold: float = 0.0) -> dict:
    """``results``: {lead: results dict}; ``references``: {lead: primary reference predictor}."""
    per_lead = {}
    for lead in sorted(results, key=int):
        res = results[lead]
        ref = references[str(lead)]
        row = comparison(res, ref)
        per_lead[str(lead)] = {
            "reference": ref, "bss": row["bss"] if row else None,
            "bss_week_lo": row["bss_week_lo"] if row else None, "bss_week_hi": row["bss_week_hi"] if row else None,
            "bss_year_lo": row["bss_year_lo"] if row else None, "bss_year_hi": row["bss_year_hi"] if row else None,
            "skill": lead_passes(row, threshold),
        }
    primary = [str(k) for k in primary_leads]
    missing = [k for k in primary if k not in per_lead]
    if missing:
        raise ValueError(f"primary leads {missing} were not scored")
    go = all(per_lead[k]["skill"] for k in primary)
    return {
        "decision": "go" if go else "no-go",
        "rule": f"BSS of '{CANDIDATE}' against the pre-registered reference > {threshold} with the paired "
                f"week-block CI lower bound > {threshold}, on every primary lead",
        "primary_leads": [int(k) for k in primary], "threshold": threshold,
        "leads_with_skill": [int(k) for k, v in per_lead.items() if v["skill"]],
        "leads_without_skill": [int(k) for k, v in per_lead.items() if not v["skill"]],
        "by_lead": per_lead,
    }


def reliability(res: dict, name: str = CANDIDATE) -> dict:
    s = next(r for r in res["summary"] if r["predictor"] == name)
    citl = s["mean_p"] - s["base_rate"]
    rows = [r for r in res["reliability"] if r["predictor"] == name]
    total = sum(r["n"] for r in rows) or 1
    big = [r for r in rows if r["n"] >= MIN_BIN_SHARE * total]
    dev = max((abs(r["obs_freq"] - r["mean_p"]) for r in big), default=float("nan"))
    return {"citl": citl, "max_bin_dev": dev,
            "ok": bool(abs(citl) <= CITL_TOL and _ok(dev) and dev <= BIN_TOL)}


def cautions(results: dict, gate: dict) -> dict:
    """Reasons to treat a lead that passed the pre-registered rule with care (reporting only; the
    decision is unchanged): year-block CI not above 0, worse than recent climatology, or miscalibrated."""
    out = {}
    for k in gate["leads_with_skill"]:
        k = str(k)
        res, g = results[k], gate["by_lead"][k]
        notes = []
        if not (_ok(g["bss_year_lo"]) and g["bss_year_lo"] > gate["threshold"]):
            notes.append("the whole-year bootstrap CI includes 0")
        rc = comparison(res, "recent_climatology")
        if rc is not None and _ok(rc["bss"]) and rc["bss"] < 0:
            notes.append(f"it is worse than recent climatology (BSS {rc['bss']:.3f})")
        if not reliability(res)["ok"]:
            notes.append("its probabilities are outside the calibration tolerance")
        if notes:
            out[k] = notes
    return out


def _slice_table(results, references, family, leads) -> list:
    out = ["| Lead | " + family.capitalize() + " | n | BSS vs reference [week CI] |", "|---|---|---|---|"]
    for lead in leads:
        res = results[str(lead)] if str(lead) in results else results[lead]
        ref = references[str(lead)]
        for r in res["slices"]:
            if r["predictor"] == CANDIDATE and r["family"] == family and r["flag_filter"] == "all_wards":
                out.append(f"| {lead} | {r['stratum']} | {r['n']:,} | {_f(r.get(f'bss_vs_{ref}'), 3)} "
                           f"{_ci(r.get(f'bss_vs_{ref}_week_lo'), r.get(f'bss_vs_{ref}_week_hi'))} |")
    return out


def render_report(results: dict, gate: dict, meta: dict) -> str:
    results = {str(k): v for k, v in results.items()}
    leads = sorted(results, key=int)
    refs = {k: gate["by_lead"][k]["reference"] for k in leads}
    go = gate["decision"] == "go"
    L = [
        "# Heatwave forecast report: single test evaluation (2021-2026)", "",
        CAPTION_TEST, "",
        f"**Decision: {gate['decision'].upper()}.** {gate['rule']} (primary leads "
        f"{', '.join(map(str, gate['primary_leads']))}).", "",
    ]
    caut = gate.get("cautions") or {}
    if go:
        L += [f"Leads with skill: {', '.join(map(str, gate['leads_with_skill'])) or 'none'}. The operational phase "
              "(Phase 15) runs for these leads only.", ""]
    else:
        no = ", ".join(map(str, gate["leads_without_skill"])) or "none"
        L += [f"**No skill beyond the best baseline at leads {no}.** The trained forecast does not beat the "
              "pre-registered reference on the primary leads, so it is not released as a skilful forecast. "
              "Recommended next step: benchmark against the ECMWF sub-seasonal (S2S) reforecasts, which carry "
              "large-scale drivers (e.g. the MJO) that ward-level reanalysis history alone cannot. Phase 15 "
              "runs only for leads that passed"
              + (f" ({', '.join(map(str, gate['leads_with_skill']))})." if gate["leads_with_skill"] else
                 ", so none at present."), ""]
    if caut:
        L += ["**Caution on the leads that passed the rule.** " + " ".join(
            f"Lead {k}: {'; '.join(v)}." for k, v in caut.items())
            + " A pass this fragile is not enough on its own to release an operational forecast; this is a "
              "reporting note and does not change the pre-registered decision.", ""]
    L += [
        "## How to read this", "",
        "- **Two layers.** The heatwave *detection* layer (which weeks are heatwave weeks) is rule-based: "
        "3+ heatwave days in the week from ERA5-Land Heat Index thresholds. The *forecast* layer is the trained "
        "model scored here. Only the forecast layer is judged in this report.",
        "- **Labels are reanalysis.** ERA5-Land, not station-confirmed observations.",
        "- **Pre-registered.** The rule, reference and model were fixed in "
        f"`docs/forecast/PREREGISTRATION.md` (git blob `{meta['preregistration_blob_sha'][:12]}…`) before the "
        f"test years were opened. The evaluation log shows {meta['test_runs']} test run(s).",
        f"- **Model.** Per lead: {', '.join(f'lead {k} {v}' for k, v in meta['model_by_lead'].items())}; "
        "refitted on 1991-2020 with frozen settings and calibrated on 2015-2020 out-of-fold predictions "
        f"(bundle sha256 `{meta['bundle_sha256'][:12]}…`).",
        "- **Reference.** The best baseline per lead, recalibrated on 2015-2020 the same way as the model.",
        "",
        "## 1. Skill by lead (all wards, 2021-2026)", "",
        "| Lead | Days ahead | Brier forecast | Reference (Brier) | BSS vs reference [week CI] [year CI] | Skill | "
        "BSS vs raw best baseline | BSS vs recent climatology |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for k in leads:
        res, g = results[k], gate["by_lead"][k]
        raw_ref = refs[k].removesuffix("_recal")
        r2, r3 = comparison(res, raw_ref), comparison(res, "recent_climatology")
        L.append(
            f"| {k} | +{targets.effective_days_ahead(int(k), meta['latency_days'])} | {_f(brier(res, CANDIDATE))} "
            f"| {refs[k]} ({_f(brier(res, refs[k]))}) | {_f(g['bss'], 3)} {_ci(g['bss_week_lo'], g['bss_week_hi'])} "
            f"{_ci(g['bss_year_lo'], g['bss_year_hi'])} | {'yes' if g['skill'] else 'no'} "
            f"| {_f(r2['bss'], 3) if r2 else 'n/a'} | {_f(r3['bss'], 3) if r3 else 'n/a'} |")
    L += [
        "", "## 2. Effective lead and skill mask", "",
        "A forecast is issued at the end of the last observed week (\"now\"); lead k targets the week starting "
        "7k - 6 days later. The real ERA5-Land delay (about 9 days) is an operational note, not part of this test.", "",
        "| Lead | Target week | Days ahead (to target Monday) | Skill mask |", "|---|---|---|---|",
    ]
    for k in leads:
        L.append(f"| {k} | issue week + {k} | +{targets.effective_days_ahead(int(k), meta['latency_days'])} "
                 f"| {'use' if gate['by_lead'][k]['skill'] else 'do not use'} |")
    L += ["", "## 3. Skill by season (exploratory)", ""] + _slice_table(results, refs, "season", leads)
    L += ["", "## 4. Skill by region (geopolitical zone, exploratory)", ""] + _slice_table(results, refs, "geozone", leads)
    L += ["", "Slices are exploratory: only the per-lead result on all wards is confirmatory.", "",
          "## 5. Calibration on the test years", "",
          f"Tolerance as in Phase 12: |mean p - observed| <= {CITL_TOL}; bins with at least "
          f"{100 * MIN_BIN_SHARE:.0f}% of rows within {BIN_TOL} of the diagonal.", "",
          "| Lead | Mean p - observed | Max bin deviation | Within tolerance |", "|---|---|---|---|"]
    for k in leads:
        r = reliability(results[k])
        L.append(f"| {k} | {_f(r['citl'], 3)} | {_f(r['max_bin_dev'], 3)} | {'yes' if r['ok'] else 'no'} |")
    L += ["", "## Provenance", "",
          f"- Test run `{meta['run_id']}`, generated {meta['generated_utc']}; bootstrap B = {meta['B']}, "
          f"week blocks of {meta['block_weeks']} weeks, seed {meta['seed']}.",
          f"- Data `{meta['data_version']}` (parquet sha256 `{meta['parquet_sha256'][:12]}…`); config sha256 "
          f"`{meta['config_sha256'][:12]}…`.",
          "- Validation evidence: `docs/forecast/LOGISTIC_VALIDATION.md`, `LIGHTGBM_VALIDATION.md`, "
          "`RECALIBRATION_VALIDATION.md`, `EXPLAINABILITY.md`.", "", GENERATED_MARKER, ""]
    return "\n".join(L)
