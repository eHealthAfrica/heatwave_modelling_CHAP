        locked_note(meta),
        "",
        f"Run `{meta['run_id']}`, generated {meta['generated_utc']}. Data `{meta['data_version']}` "
        f"(parquet sha256 `{meta['parquet_sha256'][:12]}…`), config sha256 `{meta['config_sha256'][:12]}…`, "
        f"seed {meta['seed']}, bootstrap B = {meta['B']} (week blocks of {meta['block_weeks']} weeks, and whole years). "
        f"LightGBM {meta['lightgbm_version']}, {meta['n_threads']} threads, deterministic mode.",
        "",
        "## How the models were built",
        "",
        f"- **Tuning (MODEL-02).** Expanding-window CV on the training-era folds {', '.join(map(str, meta['tune_years']))} "
        "(each fold refits the climatology and features on its own past). Within each fold, early stopping uses the "
        f"last {meta['es_weeks']} target weeks of the fold's training rows, separated from the fitting rows by the "
        f"{meta['embargo_weeks']}-week embargo. {len(meta['grid'])} strongly regularised configurations were compared "
        "per lead by mean fold Brier; the final tree count is the median early-stopping iteration.",
        "- **Calibration (MODEL-03).** Platt or isotonic per lead, chosen by leave-one-fold-out Brier on the "
        "out-of-fold predictions of the tuning folds; outputs clipped to "
        f"[{meta['clip'][0]}, {meta['clip'][1]}]. Calibration rows are the folds' held-out years, never used for "
        "fitting or early stopping. Logistic gets the same treatment for a like-for-like comparison.",
        "- **Selection.** Per lead, the candidate with the lowest CV Brier is selected, before looking at validation. "
        "The tuning folds also chose the LightGBM configuration, so the LightGBM CV Brier is slightly optimistic.",
