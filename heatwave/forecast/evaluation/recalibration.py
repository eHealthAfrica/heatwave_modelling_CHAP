"""Leave-one-year-out recalibration on the validation years (user decision 2026-10-13).

The Phase 12 calibrators were fitted on training-era folds (2010-2014), whose heatwave rate is far
below 2015-2020, so they push probabilities down. Here each validation year's predictions are
recalibrated by a calibrator fitted on the other validation years only; the model itself is not
refitted. Platt or isotonic is chosen by the leave-one-year-out Brier. The same recipe, with the
calibrator fitted on all of 2015-2020, is what Phase 14 freezes before the single test.

The 2015-2020 labels are used for calibration here, so validation is no longer a pure hold-out for
the recalibrated predictors; the locked 2021-2026 test is the clean check.
"""
from __future__ import annotations

import math
from typing import Mapping

import numpy as np

from heatwave.forecast.evaluation.baselines_report import CAPTION_VALIDATION, locked_note
from heatwave.forecast.evaluation.lightgbm_report import BIN_TOL, CITL_TOL, MIN_BIN_SHARE
from heatwave.forecast.models.calibration import Calibrator, choose_calibrator, lofo_predictions

GENERATED_MARKER = "<!-- generated by scripts/forecast_recalibrate.py -->"
SUFFIX = "_recal"
MODELS = ("logistic", "lightgbm")
BASELINE_RECAL = ("damped_persistence", "trend_season")
REF_RECENT = "recent_climatology"


def recal_name(name: str) -> str:
    return name + SUFFIX


def loyo_recalibrate(p, y, years) -> dict:
    """Leave-one-year-out calibrated probabilities plus the all-years calibrator.

    Returns ``{"q": LOYO probabilities, "method", "cv_brier", "final": Calibrator on all years}``.
    """
    years = np.asarray(years, dtype=np.int64)
    if np.unique(years).size < 2:
        raise ValueError("leave-one-year-out recalibration needs at least two years")
    final, cv = choose_calibrator(p, y, years)
    q = lofo_predictions(p, y, years, final.method)
    return {"q": q, "method": final.method, "cv_brier": cv, "final": final}


# ------------------------------------------------------------------ report
def _ok(x) -> bool:
    return x is not None and isinstance(x, (int, float)) and math.isfinite(float(x))


def _f(x, nd: int = 4) -> str:
    return f"{float(x):.{nd}f}" if _ok(x) else "n/a"


def _ci(lo, hi, nd: int = 3) -> str:
    return f"[{_f(lo, nd)}, {_f(hi, nd)}]" if _ok(lo) and _ok(hi) else "n/a"


def _cmp(res, ref, cand):
    c = res.comparisons
    row = c[(c["reference"] == ref) & (c["candidate"] == cand)]
    return None if row.empty else row.iloc[0]


def _brier(res, name):
    s = res.summary.set_index("predictor")
    return float(s.loc[name, "brier"]) if name in s.index else float("nan")


def _verdict(row) -> str:
    if row is None:
        return "n/a"
    if all(_ok(row[k]) for k in ("bss_week_lo", "bss_year_lo")) and row["bss_week_lo"] > 0 and row["bss_year_lo"] > 0:
        return "better"
    if all(_ok(row[k]) for k in ("bss_week_hi", "bss_year_hi")) and row["bss_week_hi"] < 0 and row["bss_year_hi"] < 0:
        return "worse"
    return "not distinguishable"


def _cell(row) -> str:
    if row is None:
        return "n/a"
    return f"{_f(row['bss'], 3)} {_ci(row['bss_week_lo'], row['bss_week_hi'])} {_ci(row['bss_year_lo'], row['bss_year_hi'])}"


def render_markdown(results_by_lead: Mapping[int, object], meta: dict) -> str:
    if not results_by_lead:
        raise ValueError("no lead results to render")
    leads = sorted(results_by_lead)
    L = [
        "# Recalibration on the validation years, leave-one-year-out (2015-2020)",
        "",
        CAPTION_VALIDATION,
        "",
        locked_note(meta),
        "",
        f"Run `{meta['run_id']}`, generated {meta['generated_utc']}, from the stored Phase 12 predictions of run "
        f"`{meta['source_run']}` (no model refitted). Data `{meta['data_version']}` (parquet sha256 "
        f"`{meta['parquet_sha256'][:12]}…`), config sha256 `{meta['config_sha256'][:12]}…`, seed {meta['seed']}, "
        f"bootstrap B = {meta['B']}.",
        "",
        "**Why.** The Phase 12 calibrators were fitted on 2010-2014, when heatwave weeks were much rarer than in "
        "2015-2020, so every model under-predicted. Here each validation year is recalibrated with a calibrator "
        "fitted on the other five validation years only (Platt or isotonic, chosen by the leave-one-year-out "
        "Brier). The best baselines are recalibrated the same way, so the comparison stays fair.",
        "",
        "**Caveat.** The 2015-2020 labels are now used for calibration, so the scores below are leave-one-year-out "
        "estimates, not a pure hold-out. The locked 2021-2026 test is the clean check.",
        "",
        "## 1. Calibrator chosen per lead (leave-one-year-out Brier)",
        "",
        "| Lead | Predictor | Method | LOYO Brier raw / Platt / isotonic |",
        "|---|---|---|---|",
    ]
    for lead in leads:
        for nm, c in meta["calibrators"][str(lead)].items():
            cv = c["cv_brier"]
            L.append(f"| {lead} | {nm} | {c['method']} | {_f(cv['raw'])} / {_f(cv['platt'])} / {_f(cv['isotonic'])} |")
    L += [
        "",
        "## 2. Recalibrated models against the baselines",
        "",
        "Phase 12 selected model per lead, recalibrated, against the best baseline as scored in Phase 12 and against "
        "the same baseline recalibrated.",
        "",
        "| Lead | Model | Brier | Best baseline | BSS vs best [week CI] [year CI] | Call | BSS vs best baseline recalibrated [week CI] [year CI] | Call | BSS vs recent_climatology |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for lead in leads:
        res = results_by_lead[lead]
        model = recal_name(meta["base_model"][str(lead)])
        best = meta["best_baseline_by_lead"][str(lead)]
        r1, r2, r3 = _cmp(res, best, model), _cmp(res, recal_name(best), model), _cmp(res, REF_RECENT, model)
        L.append(f"| {lead} | {model} | {_f(_brier(res, model))} | {best} ({_f(_brier(res, best))}) | {_cell(r1)} "
                 f"| {_verdict(r1)} | {_cell(r2)} | {_verdict(r2)} | {_f(r3['bss'], 3) if r3 is not None else 'n/a'} |")
    L += [
        "",
        "All recalibrated predictors (Brier):",
        "",
        "| Lead | " + " | ".join(recal_name(n) for n in MODELS + BASELINE_RECAL) + " | " + " | ".join(MODELS) + " (raw) |",
        "|---|" + "---|" * (len(MODELS) * 2 + len(BASELINE_RECAL)),
    ]
    for lead in leads:
        res = results_by_lead[lead]
        cells = [_f(_brier(res, recal_name(n))) for n in MODELS + BASELINE_RECAL] + [_f(_brier(res, n)) for n in MODELS]
        L.append(f"| {lead} | " + " | ".join(cells) + " |")
    L += [
        "",
        "## 3. Reliability after recalibration",
        "",
        f"Same tolerance as Phase 12: |mean p - observed rate| <= {CITL_TOL}, and every quantile bin holding at least "
        f"{100 * MIN_BIN_SHARE:.0f}% of rows within {BIN_TOL} of the diagonal.",
        "",
        "| Lead | Predictor | Mean p - observed | Max bin deviation | Within tolerance |",
        "|---|---|---|---|---|",
    ]
    for lead in leads:
        for nm, r in meta["reliability"][str(lead)].items():
            L.append(f"| {lead} | {nm} | {_f(r['citl'], 3)} | {_f(r['max_bin_dev'], 3)} | {'yes' if r['ok'] else 'NO'} |")
    L += [
        "",
        f"![Reliability after recalibration]({meta['figure_rel']})",
        "",
        "## Notes",
        "",
        "- The calibrators fitted on all six validation years are recorded in `docs/forecast/RECALIBRATION.json`; "
        "Phase 14 freezes this recipe (refit on 1991-2020, calibrate on 2015-2020) before the single test.",
        "- Labels are ERA5-Land reanalysis heatwave weeks (3+ heatwave days), not station-confirmed.",
        "- The heatwave detection layer is rule-based and separate from this trained forecast layer.",
    ]
    if meta.get("pin_override"):
        L += [f"- WARNING: the parquet sha256 pin was overridden: {meta['pin_override']}"]
    L += ["", GENERATED_MARKER, ""]
    return "\n".join(L)


__all__ = ["GENERATED_MARKER", "MODELS", "BASELINE_RECAL", "recal_name", "loyo_recalibrate", "render_markdown",
           "Calibrator"]
