"""Markdown report for the Phase 11 logistic-regression validation (docs/forecast/LOGISTIC_VALIDATION.md).

Validation years only. The test-lock sentence comes from the verified log counts, as in the
baselines report.
"""
from __future__ import annotations

import math
from typing import Mapping

from heatwave.forecast.evaluation.baselines_report import CAPTION_VALIDATION, locked_note

GENERATED_MARKER = "<!-- generated by scripts/forecast_logistic.py -->"
MODEL = "logistic"
SHUFFLED = "logistic_shuffled"
ABLATION_PREFIX = "logistic_ablation_"
REF_RECENT = "recent_climatology"


def _ok(x) -> bool:
    return x is not None and isinstance(x, (int, float)) and math.isfinite(float(x))


def _f(x, nd: int = 4) -> str:
    return f"{float(x):.{nd}f}" if _ok(x) else "n/a"


def _ci(lo, hi, nd: int = 3) -> str:
    return f"[{_f(lo, nd)}, {_f(hi, nd)}]" if _ok(lo) and _ok(hi) else "n/a"


def _cmp(res, ref, cand):
    c = res.comparisons
    row = c[(c["reference"] == ref) & (c["candidate"] == cand)]
    return None if row.empty else row.iloc[0]


def _brier(res, name):
    s = res.summary.set_index("predictor")
    return float(s.loc[name, "brier"]) if name in s.index else float("nan")


def verdict(row) -> str:
    """Skill call from paired BSS intervals: both block schemes must exclude zero to count."""
    if row is None:
        return "n/a"
    if _ok(row["bss_week_lo"]) and _ok(row["bss_year_lo"]) and row["bss_week_lo"] > 0 and row["bss_year_lo"] > 0:
        return "better"
    if _ok(row["bss_week_hi"]) and _ok(row["bss_year_hi"]) and row["bss_week_hi"] < 0 and row["bss_year_hi"] < 0:
        return "worse"
    return "not distinguishable"


def ablation_name(label: str) -> str:
    return ABLATION_PREFIX + label.lstrip("+")


def _headline(results, meta) -> str:
    out = [
        "| Lead | Brier logistic | Best baseline (Brier) | BSS vs best [week CI] [year CI] | Call vs best "
        "| BSS vs recent_climatology [week CI] [year CI] |",
        "|---|---|---|---|---|---|",
    ]
    for lead in sorted(results):
        res = results[lead]
        best = meta["best_baseline_by_lead"][lead]
        rb, rr = _cmp(res, best, MODEL), _cmp(res, REF_RECENT, MODEL)
        out.append(
            f"| {lead} | {_f(_brier(res, MODEL))} | {best} ({_f(_brier(res, best))}) "
            f"| {_f(rb['bss'], 3)} {_ci(rb['bss_week_lo'], rb['bss_week_hi'])} {_ci(rb['bss_year_lo'], rb['bss_year_hi'])} "
            f"| {verdict(rb)} "
            f"| {_f(rr['bss'], 3)} {_ci(rr['bss_week_lo'], rr['bss_week_hi'])} {_ci(rr['bss_year_lo'], rr['bss_year_hi'])} |"
        )
    return "\n".join(out)


def _ablation(results, meta) -> str:
    ladder = meta.get("ablation_ladder") or []
    leads = [k for k in sorted(results) if k in meta.get("ablation_leads", [])]
    if not ladder or not leads:
        return "_Ablation not run._"
    head = "| Step | Features | " + " | ".join(f"Lead {k} Brier | Lead {k} BSS vs recent [week CI]" for k in leads) + " |"
    out = [head, "|---|---|" + "---|---|" * len(leads)]
    for label, n_feat in ladder:
        name = MODEL if label == ladder[-1][0] else ablation_name(label)
        cells = []
        for k in leads:
            r = _cmp(results[k], REF_RECENT, name)
            cells.append(_f(_brier(results[k], name)))
            cells.append("n/a" if r is None else f"{_f(r['bss'], 3)} {_ci(r['bss_week_lo'], r['bss_week_hi'])}")
        out.append(f"| {label} | {n_feat} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def _control(results, meta) -> str:
    out = [
        "| Lead | BSS logistic vs recent | BSS shuffled vs recent [week CI] | BSS shuffled vs best [week CI] [year CI] | Control |",
        "|---|---|---|---|---|",
    ]
    for lead in sorted(results):
        res = results[lead]
        best = meta["best_baseline_by_lead"][lead]
        m, sr, sb = _cmp(res, REF_RECENT, MODEL), _cmp(res, REF_RECENT, SHUFFLED), _cmp(res, best, SHUFFLED)
        if sb is None:
            continue
        ok = meta["control"][lead]["ok"]
        out.append(
            f"| {lead} | {_f(m['bss'], 3)} | {_f(sr['bss'], 3)} {_ci(sr['bss_week_lo'], sr['bss_week_hi'])} "
            f"| {_f(sb['bss'], 3)} {_ci(sb['bss_week_lo'], sb['bss_week_hi'])} {_ci(sb['bss_year_lo'], sb['bss_year_hi'])} "
            f"| {'pass' if ok else 'FAIL'} |"
        )
    return "\n".join(out)


def _murphy(results) -> str:
    out = ["| Lead | Predictor | Brier | Reliability | Resolution | Mean p | Observed rate |", "|---|---|---|---|---|---|---|"]
    for lead in sorted(results):
        s = results[lead].summary.set_index("predictor")
        for nm in (MODEL, SHUFFLED):
            if nm in s.index:
                r = s.loc[nm]
                out.append(
                    f"| {lead} | {nm} | {_f(r['brier'])} | {_f(r['rel'], 5)} | {_f(r['res'], 5)} "
                    f"| {_f(r['mean_p'], 3)} | {_f(r['base_rate'], 3)} |"
                )
    return "\n".join(out)


def _coefs(meta, n=10) -> str:
    coefs = meta.get("coefficients") or {}
    if not coefs:
        return "_No coefficients recorded._"
    leads = sorted(coefs)[:2]
    out = ["| Rank | " + " | ".join(f"Lead {k} feature | coef" for k in leads) + " |",
           "|---|" + "---|---|" * len(leads)]
    for i in range(n):
        cells = []
        for k in leads:
            if i < len(coefs[k]):
                nm, c = coefs[k][i]
                cells += [f"`{nm}`", f"{c:+.3f}"]
            else:
                cells += ["", ""]
        out.append(f"| {i + 1} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def render_markdown(results_by_lead: Mapping[int, object], meta: dict) -> str:
    decay = meta.get("decay_check") or {}
    primary = meta.get("primary_leads", [])
    if not results_by_lead:
        raise ValueError("no lead results to render")
    lines = [
        "# Logistic regression: validation scores (2015-2020)",
        "",
        CAPTION_VALIDATION,
        "",
        locked_note(meta),
        "",
        f"Run `{meta['run_id']}`, generated {meta['generated_utc']}. Data `{meta['data_version']}` "
        f"(parquet sha256 `{meta['parquet_sha256'][:12]}…`), config sha256 `{meta['config_sha256'][:12]}…`, "
        f"seed {meta['seed']}, bootstrap B = {meta['B']} (week blocks of {meta['block_weeks']} weeks, and whole years).",
        "",
        "One L2-regularised logistic regression per lead, fitted on training targets only "
        f"(before {meta['train_end']}), on a seeded subsample of at most {meta['max_train_rows']:,} rows per lead, "
        f"with {meta['n_features']} standardised features. Scored on the validation years only "
        f"({meta['n_wards']} wards). Baselines are refitted in the same run.",
        "",
        "**Reading the calls.** \"Better\" means the paired BSS interval excludes zero under both the "
        "4-week block and the whole-year bootstrap. The go/no-go judgement uses leads "
        f"{', '.join(str(k) for k in primary)}.",
        "",
        "## 1. Skill against the baselines",
        "",
        _headline(results_by_lead, meta),
        "",
        "## 2. Ablation ladder (cumulative feature groups)",
        "",
        "Each step adds a feature group to the previous one; the last step is the full model.",
        "",
        _ablation(results_by_lead, meta),
        "",
        "## 3. Negative control: year-shuffled features",
        "",
        "Each origin's weather and trend features are taken from the same ISO week of a different "
        "random year in the same split; season, location and the labels are left true. A model that "
        "reads the current weather should lose its edge. The control passes when the shuffled model "
        "is not better than the best baseline (week-block lower bound of its BSS at or below zero).",
        "",
        _control(results_by_lead, meta),
        "",
        "## 4. Skill decay with lead",
        "",
        (
            f"BSS of logistic vs recent_climatology: lead {decay.get('lead_first')} {_f(decay.get('bss_first'), 3)}, "
            f"lead {decay.get('lead_last')} {_f(decay.get('bss_last'), 3)}. "
            f"Decay check {'passes' if decay.get('ok') else 'FAILS'}"
            f"{' (strictly decreasing across leads)' if decay.get('strictly_monotone') else ''}."
            if decay else "_Decay check needs at least two leads._"
        ),
        "",
        "## 5. Calibration (Murphy decomposition)",
        "",
        _murphy(results_by_lead),
        "",
        "## 6. Largest standardised coefficients",
        "",
        "Coefficients are per one standard deviation of the training sample. They describe the fitted "
        "model, not causes: correlated features share weight.",
        "",
        _coefs(meta),
        "",
        "## Notes",
        "",
        "- Labels are ERA5-Land reanalysis heatwave weeks (3+ heatwave days), not station-confirmed.",
        "- The heatwave detection layer is rule-based and separate from this trained forecast layer.",
    ]
    if meta.get("pin_override"):
        lines += [f"- WARNING: the parquet sha256 pin was overridden: {meta['pin_override']}"]
    lines += ["", GENERATED_MARKER, ""]
    return "\n".join(lines)
