"""Markdown renderer for the baseline validation scores (docs/forecast/BASELINES_VALIDATION.md).

Pure formatting over ``harness.LeadResult`` objects: it computes no statistic of its own and
claims no interval the harness does not compute. Validation years only; the test years are
locked and unscored.
"""

from __future__ import annotations

import math
from typing import Mapping

import numpy as np
import pandas as pd

from heatwave.forecast.evaluation import slices
from heatwave.forecast.report import CAPTION, _table

__all__ = ["CAPTION_VALIDATION", "LOCKED_NOTE", "GENERATED_MARKER", "render_markdown"]

CAPTION_VALIDATION = CAPTION + "; validation 2015-2020"
LOCKED_NOTE = (
    "Test years 2021-2026 are locked and unscored: no test-split row was loaded or scored in this run "
    "(evaluation log test runs: {n})."
)
GENERATED_MARKER = "<!-- generated by scripts/forecast_baselines.py -->"

REF_CLIM = "climatology"
REF_RECENT = "recent_climatology"
BSS_BEST_COL = "BSS best baseline vs recent_climatology [week CI]"
FILTER_LABELS = {
    "all_wards": "all wards",
    "large_wards_only": "large wards only",
    "exclude_lga_average": "excluding LGA-average wards",
    "lga_average_only": "LGA-average wards",
}


# ------------------------------------------------------------------ formatting helpers
def _ok(x) -> bool:
    return x is not None and not (isinstance(x, float) and math.isnan(x)) and not pd.isna(x)


def _f(x, nd: int = 4) -> str:
    return f"{float(x):.{nd}f}" if _ok(x) else "n/a"


def _ci(lo, hi, nd: int = 4) -> str:
    return f"[{float(lo):.{nd}f}, {float(hi):.{nd}f}]" if _ok(lo) and _ok(hi) else "n/a"


def _order(results: Mapping[int, object]) -> list:
    return sorted(results)


def _predictors(results) -> list:
    return list(results[min(results)].predictors)


def _names_in_order(results, meta) -> list:
    order = list(meta.get("baseline_order") or [])
    have = _predictors(results)
    return [p for p in order if p in have] + [p for p in have if p not in order]


def _best_cell(meta, lead):
    return (meta.get("best_baseline_by_lead") or {}).get(lead)


# ------------------------------------------------------------------------ section tables
def _best_table(results, meta, names) -> str:
    rows = []
    for k in _order(results):
        best = _best_cell(meta, k)
        s = results[k].summary.set_index("predictor")
        rows.append({"lead": k, "predictor": best, "Brier": _f(s.loc[best, "brier"]) if best in s.index else "n/a"})
    return _table(pd.DataFrame(rows))


def _brier_wide(results, names) -> str:
    rows = []
    for k in _order(results):
        s = results[k].summary.set_index("predictor")
        row = {"lead": k}
        for nm in names:
            row[nm] = _f(s.loc[nm, "brier"])
        rows.append(row)
    return _table(pd.DataFrame(rows))


def _brier_ci(results, names) -> str:
    rows = []
    for k in _order(results):
        s = results[k].summary.set_index("predictor")
        for nm in names:
            r = s.loc[nm]
            rows.append({
                "lead": k, "predictor": nm, "Brier": _f(r["brier"]),
                "week-block CI": _ci(r["brier_week_lo"], r["brier_week_hi"]),
                "year-block CI": _ci(r["brier_year_lo"], r["brier_year_hi"]),
            })
    return _table(pd.DataFrame(rows))


def _skill(results, ref) -> str:
    rows = []
    for k in _order(results):
        c = results[k].comparisons
        c = c[(c["reference"] == ref) & (c["candidate"] != ref)]
        for _, r in c.iterrows():
            rows.append({
                "lead": k, "candidate": r["candidate"], "BSS": _f(r["bss"]),
                "BSS week-block CI": _ci(r["bss_week_lo"], r["bss_week_hi"]),
                "BSS year-block CI": _ci(r["bss_year_lo"], r["bss_year_hi"]),
                "dBS": _f(r["dbs"]),
                "dBS week-block CI": _ci(r["dbs_week_lo"], r["dbs_week_hi"]),
            })
    return _table(pd.DataFrame(rows))


def _decomposition(results, names) -> str:
    rows = []
    for k in _order(results):
        s = results[k].summary.set_index("predictor")
        for nm in names:
            r = s.loc[nm]
            rows.append({
                "lead": k, "predictor": nm,
                "REL": _f(r["rel"]), "REL week-block CI": _ci(r["rel_week_lo"], r["rel_week_hi"]),
                "RES": _f(r["res"]), "RES week-block CI": _ci(r["res_week_lo"], r["res_week_hi"]),
                "UNC": _f(r["unc"]), "residual": _f(r["residual"], 6),
            })
    return _table(pd.DataFrame(rows))


def _slice_rows(res, family, flag_filter):
    s = res.slices
    return s[(s["family"] == family) & (s["flag_filter"] == flag_filter)]


def _brier_cells(sub, names):
    by = sub.set_index("predictor")
    return {nm: (_f(by.loc[nm, "brier"]) if nm in by.index else "n/a") for nm in names}


def _season_table(results, meta, names) -> str:
    rows = []
    for k in _order(results):
        best = _best_cell(meta, k)
        sl = _slice_rows(results[k], "season", "all_wards")
        for season in slices.SEASONS:
            sub = sl[sl["stratum"] == season]
            if sub.empty:
                continue
            label = f"**{season}** (highlighted)" if season == slices.HIGHLIGHT_SEASON else season
            row = {"lead": k, "season": label, "n": int(sub["n"].iloc[0])}
            row.update(_brier_cells(sub, names))
            b = sub[sub["predictor"] == best]
            col = f"bss_vs_{REF_RECENT}"
            if len(b) and col in b.columns:
                row[BSS_BEST_COL] = (
                    f"{_f(b[col].iloc[0])} {_ci(b[col + '_week_lo'].iloc[0], b[col + '_week_hi'].iloc[0])}"
                )
            else:
                row[BSS_BEST_COL] = "n/a"
            rows.append(row)
    return _table(pd.DataFrame(rows))


def _region_table(results, names) -> str:
    rows = []
    for k in _order(results):
        res = results[k]
        for fam, label in (("geozone", "geozone"), ("lat_band", "latitude band")):
            sl = _slice_rows(res, fam, "all_wards")
            for stratum in sl["stratum"].drop_duplicates():
                sub = sl[sl["stratum"] == stratum]
                row = {"lead": k, "family": label, "stratum": stratum, "n": int(sub["n"].iloc[0])}
                row.update(_brier_cells(sub, names))
                rows.append(row)
        for ff in slices.FLAG_FILTERS:
            sub = _slice_rows(res, "all", ff)
            if sub.empty:
                continue
            row = {"lead": k, "family": "ward filter", "stratum": FILTER_LABELS[ff], "n": int(sub["n"].iloc[0])}
            row.update(_brier_cells(sub, names))
            rows.append(row)
    return _table(pd.DataFrame(rows))


def _citl_table(results, names) -> str:
    rows = []
    for k in _order(results):
        c = results[k].citl
        for year in sorted(c["year"].unique()):
            sub = c[c["year"] == year].set_index("predictor")
            first = sub.iloc[0]
            row = {"lead": k, "year": int(year), "observed": _f(first["obs"])}
            for nm in names:
                row[nm] = f"{float(sub.loc[nm, 'citl']):+.4f}" if nm in sub.index and _ok(sub.loc[nm, "citl"]) else "n/a"
            rows.append(row)
    return _table(pd.DataFrame(rows))


def _auc_table(results, names, leads) -> str:
    rows = []
    for k in leads:
        a = results[k].auc
        for (fam, stratum), sub in a.groupby(["family", "stratum"], sort=False):
            by = sub.set_index("predictor")
            first = sub.iloc[0]
            row = {"lead": k, "family": fam, "stratum": stratum, "n": int(first["n"]), "n_pos": int(first["n_pos"])}
            for nm in names:
                row[nm] = _f(by.loc[nm, "auc"]) if nm in by.index else "n/a"
            rows.append(row)
    return _table(pd.DataFrame(rows))


def _reliability_table(results, meta, leads) -> str:
    rows = []
    for k in leads:
        best = _best_cell(meta, k)
        r = results[k].reliability
        r = r[r["predictor"] == best]
        for _, x in r.iterrows():
            rows.append({
                "lead": k, "predictor": best, "bin": int(x["bin"]), "n": int(x["n"]),
                "forecast range": f"[{float(x['p_lo']):.4f}, {float(x['p_hi']):.4f}]",
                "mean forecast": _f(x["mean_p"]), "observed frequency": _f(x["obs_freq"]),
            })
    return _table(pd.DataFrame(rows))


def _prf_table(results, names) -> str:
    rows = []
    for k in _order(results):
        p = results[k].prf.set_index("predictor")
        for nm in names:
            r = p.loc[nm]
            rows.append({
                "lead": k, "predictor": nm, "threshold": _f(r["threshold"]),
                "predicted-positive rate": _f(r["predicted_positive_rate"]), "prevalence": _f(r["prevalence"]),
                "precision": f"{_f(r['precision'])} {_ci(r['precision_week_lo'], r['precision_week_hi'], 3)}",
                "recall": f"{_f(r['recall'])} {_ci(r['recall_week_lo'], r['recall_week_hi'], 3)}",
                "F1": f"{_f(r['f1'])} {_ci(r['f1_week_lo'], r['f1_week_hi'], 3)}",
            })
    return _table(pd.DataFrame(rows))


# ---------------------------------------------------------------------------- the report
def render_markdown(results_by_lead: Mapping[int, object], meta: dict) -> str:
    results = dict(results_by_lead)
    if not results:
        raise ValueError("no lead results to render")
    names = _names_in_order(results, meta)
    leads = _order(results)
    auc_leads = [k for k in leads if k in (1, 2)] or leads[:2]
    m = int(meta.get("shrinkage_pseudo_count", 0))
    n_wards = meta.get("n_wards")
    n_small = meta.get("n_small_wards")
    n_large = meta.get("n_large_wards")
    L: list = []
    add = L.append

    add("# Baseline validation scores (2015-2020)")
    add("")
    add(CAPTION_VALIDATION)
    add("")
    add(LOCKED_NOTE.format(n=meta.get("test_runs", 0)))
    add("")
    add("## Provenance")
    add("")
    for key, label in (
        ("run_id", "Run"), ("generated_utc", "Generated (UTC)"), ("data_version", "Data version"),
        ("parquet_sha256", "Parquet SHA-256"), ("config_sha256", "Config SHA-256"), ("seed", "Seed"),
        ("B", "Bootstrap replicates"), ("block_weeks", "Block length (weeks)"), ("ci_level", "CI level"),
        ("reliability_bins", "Reliability bins (quantile)"), ("shrinkage_pseudo_count", "Shrinkage pseudo-count m"),
    ):
        if key in meta:
            add(f"- {label}: {meta[key]}")
    if n_wards is not None:
        add(f"- Wards: {n_wards} ({n_large} large, {n_small} small by geometry area)")
    add("- Scoring: every predictor, baselines included, is scored from its stored prediction file by the same harness.")
    add("")

    add("## Best baseline per lead")
    add("")
    gate_leads = meta.get("primary_leads")
    extra = f" at the gate primary leads {list(gate_leads)}" if gate_leads else ""
    add(
        "The best baseline is the predictor with the lowest validation Brier score (ties by configured order). "
        f"The Phase 14 gate uses it as its reference{extra}."
    )
    add("")
    add(_best_table(results, meta, names))
    add("")

    add("## Brier by lead")
    add("")
    add("Lower is better. Climatology-referenced skill is below.")
    add("")
    add(_brier_wide(results, names))
    add("")
    add("### Brier with intervals")
    add("")
    add("Week-block and year-block intervals from the paired bootstrap (percentile).")
    add("")
    add(_brier_ci(results, names))
    add("")

    add("## Skill against climatology")
    add("")
    add("BSS = 1 - BS(candidate) / BS(climatology). dBS = BS(climatology) - BS(candidate); positive means the candidate is better.")
    add("")
    add(_skill(results, REF_CLIM))
    add("")
    add("## Skill against recent climatology")
    add("")
    add("BSS = 1 - BS(candidate) / BS(recent_climatology), same sign convention.")
    add("")
    add(_skill(results, REF_RECENT))
    add("")

    add("## Brier decomposition")
    add("")
    add(
        "REL (reliability) and RES (resolution) use the full-sample quantile bin edges of each predictor; "
        "their week-block intervals are conditional on those bin edges. UNC is the uncertainty term and "
        "residual is BS - (REL - RES + UNC)."
    )
    add("")
    add(_decomposition(results, names))
    add("")

    add("## Season (MAM highlighted)")
    add("")
    add("All wards, all six leads. Season is assigned by the mid-week day of the target week. Slice intervals are exploratory.")
    add("")
    add(_season_table(results, meta, names))
    add("")

    add("## Region")
    add("")
    add(
        "All six leads. Geozone and latitude band use all wards; the ward-filter rows compare all wards, "
        "large wards only, excluding LGA-average wards, and LGA-average wards. Slice intervals are exploratory."
    )
    add("")
    add(_region_table(results, names))
    add("")

    add("## Calibration-in-the-large by year")
    add("")
    add("Mean forecast minus observed frequency per target year (point values, no interval).")
    add("")
    add(_citl_table(results, names))
    add("")

    add("## Stratified ROC AUC")
    add("")
    add(f"Leads {auc_leads}. Stratified by season, geozone and latitude band; there is no pooled AUC.")
    add("")
    add(_auc_table(results, names, auc_leads))
    add("")

    add("## Reliability")
    add("")
    add(f"Quantile bins for the best baseline at leads {auc_leads}.")
    add("")
    add(_reliability_table(results, meta, auc_leads))
    add("")

    add("## Precision / recall / F1 at a stated threshold")
    add("")
    add(
        "The threshold is the training base rate of the lead. It is reported with the predicted-positive rate "
        "and the prevalence, and is never used to rank predictors. Intervals are week-block."
    )
    add("")
    add(_prf_table(results, names))
    add("")

    add("## Sanity checks")
    add("")
    dc = meta.get("decay_check") or {}
    if dc:
        add(
            f"- Persistence decay check: BSS vs climatology at lead {dc.get('lead_first')} = {_f(dc.get('bss_first'))}, "
            f"at lead {dc.get('lead_last')} = {_f(dc.get('bss_last'))}; "
            f"{'passes' if dc.get('ok') else 'FAILS'} (shortest-lead skill must exceed longest-lead skill); "
            f"strictly monotone across leads: {'yes' if dc.get('strictly_monotone') else 'no'} (warning only)."
        )
    add("- BSS(reference, reference) = 0 with a zero-width interval for each reference (included in the stored results).")
    sanity = meta.get("sanity") or {}
    for k in leads:
        s = sanity.get(k) or sanity.get(str(k))
        if s:
            add(
                f"- Lead {k}: probabilities valid = {'yes' if s.get('probabilities_valid') else 'NO'}; "
                f"self-BSS zero = {'yes' if s.get('self_bss_zero') else 'NO'}."
            )
    add("")

    add("## Notes")
    add("")
    mp = meta.get("mean_p_vs_obs")
    if not mp:
        s1 = results[leads[0]].summary.set_index("predictor")
        mp = {nm: (float(s1.loc[nm, "mean_p"]), float(s1.loc[nm, "base_rate"])) for nm in names}
    if REF_CLIM in mp:
        v = mp[REF_CLIM]
        mean_p, obs = (v if isinstance(v, (tuple, list)) else (v.get("mean_p"), v.get("obs")))
        add(
            f"- Static climatology is a strawman: at lead {leads[0]} it predicts a mean of {_f(mean_p, 3)} "
            f"against {_f(obs, 3)} observed on the validation years."
        )
    add("- trend_season extrapolates the linear logit trend fitted on 1991-2014 into 2015-2020.")
    add(
        f"- recent_climatology shrinks the as-of base rate with a fixed pseudo-count m = {m}, chosen a priori; "
        "a larger m was marginally better on the backtest and on validation by less than the CI half-width."
    )
    add("- The year-block interval rests on 6 clusters (validation years) and is a coarse check only.")
    add("- Slice intervals (season, region, ward filters) are exploratory and not adjusted for multiplicity.")
    add("- REL and RES week-block intervals are conditional on the full-sample quantile bin edges.")
    add("- Calibration-in-the-large by year is shown as point values without intervals.")
    if n_wards is not None and n_small is not None and n_wards:
        add(
            f"- Small wards (geometry area below one 0.1 x 0.1 degree cell) are {n_small} of {n_wards} "
            f"({100.0 * float(n_small) / float(n_wards):.1f}%); the region table shows large wards only for comparison."
        )
    add("- Labels come from ERA5-Land reanalysis, not station observations.")

    return "\n".join(L).rstrip("\n") + "\n\n" + GENERATED_MARKER + "\n"
